const assert=require('node:assert/strict');
const C=require('../shared/core.js');
const now=Date.parse('2026-10-30T18:00:00Z');
const start={id:'one',type:'start',payload:{id:'sleep-1',childId:'avi',start:now-600000}};
let s=C.apply(C.initial(),start,now);
assert.equal(C.active(s,'avi').id,'sleep-1');
assert.throws(()=>C.apply(s,{type:'start',payload:{id:'sleep-2',childId:'avi',start:now}},now),/already started/);
assert.throws(()=>C.apply(s,{type:'end',payload:{id:'sleep-1',childId:'avi',end:now,expectedRev:2}},now),/changed/);
s=C.apply(s,{type:'end',payload:{id:'sleep-1',childId:'avi',end:now,expectedRev:1}},now);
assert.equal(s.entries[0].end,now);
assert.throws(()=>C.apply(s,{type:'add',payload:{id:'overlap',childId:'avi',start:now-500000,end:now}},now),/overlaps/);
assert.throws(()=>C.apply(s,{type:'edit',payload:{id:'sleep-1',childId:'avi',start:now,end:now-1,expectedRev:2}},now),/after start/);
s=C.apply(s,{type:'delete',payload:{id:'sleep-1',childId:'avi',expectedRev:2}},now);
assert.equal(s.entries[0].deleted,true);
assert.throws(()=>C.apply(s,{type:'archive',payload:{childId:'avi',archived:true}},now),/at least one/);
s=C.apply(s,{type:'child',payload:{id:'child-other',name:'Other'}},now);
s=C.apply(s,{type:'archive',payload:{childId:'child-other',archived:true}},now);
assert.throws(()=>C.apply(s,{type:'start',payload:{id:'x',childId:'child-other',start:now}},now),/unavailable/);
const day=Date.parse('2026-10-30T16:00:00Z');
let d=C.apply(C.initial(),{type:'start',payload:{id:'day',childId:'avi',start:day}},day);
C.settle(d,day+4*3600000);assert.equal(d.entries[0].end,day+90*60000);assert.equal(d.entries[0].autoEnded,true);
const night=Date.parse('2026-10-31T04:00:00Z');
let n=C.apply(C.initial(),{type:'start',payload:{id:'night',childId:'avi',start:night}},night);
C.settle(n,night+11*3600000);assert.equal(n.entries[0].end,null);
C.settle(n,night+12*3600000);assert.equal(n.entries[0].end,night+4*3600000);
assert.throws(()=>C.apply(C.initial(),{type:'settings',payload:{expectedRevision:0,settings:{dayReplace:500}}},now),/must not exceed/);
assert.throws(()=>C.apply(C.initial(),{type:'settings',payload:{expectedRevision:1,settings:{dayStart:6}}},now),/changed/);
console.log('PASS core: duplicate starts, stale revisions, overlaps, delete, children, archive protection, day/night auto-end and settings validation');
